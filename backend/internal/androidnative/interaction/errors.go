func MapInteractionErrorToCanonical(code string) string {
	switch code {
	case INTERACTION_UNSUPPORTED:
		return "PLATFORM_NOT_SUPPORTED"
	case INTERACTION_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_INVALID_REQUEST:
		return "AUTHORIZATION_DENIED"
	case INTERACTION_NODE_NOT_FOUND:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_NODE_STALE:
		return "BRIDGE_INVALID_RESPONSE"
	case INTERACTION_CONTEXT_CHANGED:
		return "BRIDGE_INVALID_RESPONSE"
	case INTERACTION_ACTION_UNSUPPORTED:
		return "PLATFORM_NOT_SUPPORTED"
	case INTERACTION_ACTION_FAILED:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_OUTCOME_UNKNOWN:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_COORDINATE_INVALID:
		return "AUTHORIZATION_DENIED"
	case INTERACTION_DISPLAY_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_TEXT_INPUT_UNSUPPORTED:
		return "PLATFORM_NOT_SUPPORTED"
	case INTERACTION_SENSITIVE_INPUT_DENIED:
		return "AUTHORIZATION_DENIED"
	case INTERACTION_VISUAL_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_SCREENSHOT_FAILED:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_VISUAL_TARGET_NOT_FOUND:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_VISUAL_TARGET_AMBIGUOUS:
		return "BRIDGE_INVALID_RESPONSE"
	case INTERACTION_VISUAL_STATE_STALE:
		return "BRIDGE_INVALID_RESPONSE"
	case INTERACTION_ROOT_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_ADB_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_VERIFICATION_FAILED:
		return "PROVIDER_UNAVAILABLE"
	case INTERACTION_TIMEOUT:
		return "BRIDGE_TIMEOUT"
	case INTERACTION_CANCELLED:
		return "CANCELLED"
	case INTERACTION_NATIVE_HOST_UNAVAILABLE:
		return "PROVIDER_UNAVAILABLE"
	default:
		return "PROVIDER_UNAVAILABLE"
	}
}

