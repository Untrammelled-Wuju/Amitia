	INTERACTION_COORDINATE_INVALID    = "INTERACTION_COORDINATE_INVALID"
	INTERACTION_DISPLAY_UNAVAILABLE   = "INTERACTION_DISPLAY_UNAVAILABLE"

	INTERACTION_TEXT_INPUT_UNSUPPORTED   = "INTERACTION_TEXT_INPUT_UNSUPPORTED"
	INTERACTION_SENSITIVE_INPUT_DENIED   = "INTERACTION_SENSITIVE_INPUT_DENIED"

	INTERACTION_VISUAL_UNAVAILABLE        = "INTERACTION_VISUAL_UNAVAILABLE"
	INTERACTION_SCREENSHOT_FAILED         = "INTERACTION_SCREENSHOT_FAILED"
	INTERACTION_VISUAL_TARGET_NOT_FOUND   = "INTERACTION_VISUAL_TARGET_NOT_FOUND"
