func mapBrowserDomainError(err error) *capability.ToolError {
	if err == nil {
		return nil
	}
	browserErr, ok := err.(*browser.BrowserError)
	if !ok {
		return &capability.ToolError{
			Code:        capability.ErrorCodeExecutionFailed,
			Message:     err.Error(),
			UserVisible: false,
		}
	}
	code := capability.ErrorCodeExecutionFailed
	retryable := false
	switch browserErr.Code {
	case browser.ErrCodeInvalidInput:
		code = capability.ErrorCodeInvalidInput
	case browser.ErrCodePermissionDenied:
		code = capability.ErrorCodePermissionDenied
	case browser.ErrCodeSessionNotFound,
		browser.ErrCodeTabNotFound,
		browser.ErrCodeBrowserExecNotFound:
		code = capability.ErrorCodeNotAvailable
	case browser.ErrCodeBrowserDisabled,
		browser.ErrCodeBrowserRuntimeNotReady,
		browser.ErrCodeProviderUnavailable:
		code = capability.ErrorCodeRuntimeUnavailable
	case browser.ErrCodeSessionLimitReached,
		browser.ErrCodeTabQuotaReached:
		code = capability.ErrorCodeRateLimited
	case browser.ErrCodeUnsupportedAction:
		code = capability.ErrorCodeNotAvailable
	case browser.ErrCodeNavigationTimeout,
		browser.ErrCodeDownloadTimeout:
		code = capability.ErrorCodeTimeout
		retryable = true
	case browser.ErrCodeStaleElement,
		browser.ErrCodeSessionStale,
		browser.ErrCodeTabStale:
		retryable = true
	}
	return &capability.ToolError{
		Code:        code,
		Message:     browserErr.Message,
		DomainCode:  string(browserErr.Code),
		Retryable:   retryable,
		UserVisible: true,
		Cause:       browserErr.Unwrap(),
	}
}
