func registerBrowserTools(registry *capability.ToolRegistry, provider browser.BrowserProvider) error {
	if registry == nil || provider == nil {
		return nil
	}
	caps := provider.BrowserCapabilities()
	tools := buildBrowserToolDefinitions(caps)
	for _, def := range tools {
		if err := registry.Replace(context.Background(), def); err != nil {
			return err
		}
	}
	return nil
}

